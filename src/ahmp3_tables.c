void ahmp3_tables_init(ahmp3_tables *t)
{
    for (int i = 0; i <= 256; i++) t->D[i] = (float)(ahmp3_window_half[i] / 65536.0);
    for (int i = 1; i < 256; i++) t->D[512 - i] = (i & 63) ? -t->D[i] : t->D[i];

    for (int k = 0; k < 18; k++)
        for (int i = 0; i < 36; i++)
            t->imdct_long[k][i] = (float)cos(AHMP3_PI / 72 * (2 * i + 1 + 18) * (2 * k + 1));
    for (int k = 0; k < 6; k++)
        for (int i = 0; i < 12; i++)
            t->imdct_short[k][i] = (float)cos(AHMP3_PI / 24 * (2 * i + 1 + 6) * (2 * k + 1));

    /* Windows by block type: 0 normal, 1 start, 2 short (12 points), 3 stop. */
    for (int i = 0; i < 36; i++) t->win[0][i] = (float)sin(AHMP3_PI / 36 * (i + 0.5));
    for (int i = 0; i < 18; i++) t->win[1][i] = t->win[0][i];
    for (int i = 18; i < 24; i++) t->win[1][i] = 1;
    for (int i = 24; i < 30; i++) t->win[1][i] = (float)sin(AHMP3_PI / 12 * (i - 18 + 0.5));
    for (int i = 30; i < 36; i++) t->win[1][i] = 0;
    memset(t->win[2], 0, sizeof(t->win[2]));
    for (int i = 0; i < 12; i++) t->win[2][i] = (float)sin(AHMP3_PI / 12 * (i + 0.5));
    for (int i = 0; i < 6; i++) t->win[3][i] = 0;
    for (int i = 6; i < 12; i++) t->win[3][i] = (float)sin(AHMP3_PI / 12 * (i - 6 + 0.5));
    for (int i = 12; i < 18; i++) t->win[3][i] = 1;
    for (int i = 18; i < 36; i++) t->win[3][i] = t->win[0][i];

    static const double ci[8] = {-0.6, -0.535, -0.33, -0.185, -0.095, -0.041, -0.0142, -0.0037};
    for (int i = 0; i < 8; i++) {
        double s = sqrt(1 + ci[i] * ci[i]);
        t->cs[i] = (float)(1 / s);
        t->ca[i] = (float)(ci[i] / s);
    }
    for (int i = 0; i < 8207; i++) t->pow43[i] = (float)pow(i, 4.0 / 3.0);
}

bool ahmp3_read_header(const unsigned char *p, ahmp3_header *h)
{
    if (p[0] != 0xFF || (p[1] & 0xE0) != 0xE0) return false;
    int version = (p[1] >> 3) & 3; /* 0 = 2.5, 1 reserved, 2 = MPEG-2, 3 = MPEG-1 */
    int layer = (p[1] >> 1) & 3;   /* 1 = Layer III */
    int br = p[2] >> 4, sr = (p[2] >> 2) & 3;
    if (version == 1 || layer != 1 || br == 0 || br == 15 || sr == 3) return false;
    memset(h, 0, sizeof(*h));
    h->lsf = version != 3;
    h->mpeg25 = version == 0;
    h->sr_index = sr + (version == 3 ? 0 : version == 2 ? 3 : 6);
    h->bitrate_index = br;
    h->crc = !(p[1] & 1);
    h->padding = (p[2] >> 1) & 1;
    h->mode = p[3] >> 6;
    h->mode_ext = (p[3] >> 4) & 3;
    h->channels = h->mode == 3 ? 1 : 2;
    int rate = ahmp3_sample_rates[h->sr_index];
    int kbps = ahmp3_bitrates[h->lsf][br];
    h->frame_bytes = (h->lsf ? 72000 : 144000) * kbps / rate + h->padding;
    h->side_bytes = h->lsf ? (h->channels == 1 ? 9 : 17) : (h->channels == 1 ? 17 : 32);
    return h->frame_bytes > 4 + 2 * h->crc + h->side_bytes;
}

bool ahmp3_parse_header(const uint8_t *data, size_t len, ahmp3_frame *frame)
{
    ahmp3_header h;
    if (len < 4 || !ahmp3_read_header(data, &h)) return false;
    if (frame) {
        frame->version = h.mpeg25 ? 25 : h.lsf ? 2 : 1;
        frame->sample_rate = ahmp3_sample_rates[h.sr_index];
        frame->channels = h.channels;
        frame->bitrate_kbps = ahmp3_bitrates[h.lsf][h.bitrate_index];
        frame->frame_bytes = h.frame_bytes;
        frame->samples = h.lsf ? 576 : 1152;
    }
    return true;
}

size_t ahmp3_id3v2_size(const uint8_t *d, size_t len)
{
    if (len < 10 || d[0] != 'I' || d[1] != 'D' || d[2] != '3' || d[3] == 0xFF || d[4] == 0xFF) return 0;
    if ((d[6] | d[7] | d[8] | d[9]) & 0x80) return 0;
    size_t size = ((size_t)d[6] << 21) | ((size_t)d[7] << 14) | ((size_t)d[8] << 7) | d[9];
    return size + 10 + ((d[5] & 0x10) ? 10 : 0); /* footer */
}

void ahmp3_to_s16(const float *in, int16_t *out, size_t count)
{
    for (size_t i = 0; i < count; i++) {
        float v = in[i] * 32768.0f;
        v += v >= 0 ? 0.5f : -0.5f;
        if (v > 32767.0f) v = 32767.0f;
        if (v < -32768.0f) v = -32768.0f;
        out[i] = (int16_t)v;
    }
}
